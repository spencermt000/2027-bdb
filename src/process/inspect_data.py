"""Milestone 1 data inspection. Writes outputs/data_inspection.md.

Usage: python src/process/inspect_data.py
"""
import numpy as np
import pandas as pd

from config import paths
from loaders import DRILLS, load_results, load_tracking

BIO_COLS = ["combine_height", "combine_weight", "hand_size", "arm_length", "wing_span",
            "combine_position", "ngs_college_production_score", "ngs_athleticism_score",
            "ten_yd_split", "forty", "short_shuttle", "three_cone"]
START_MOVE_YD = 1.0   # displacement along x that defines the start of the first leg


def md_table(df: pd.DataFrame) -> str:
    return df.to_markdown() if hasattr(df, "to_markdown") and _has_tabulate() else "```\n" + df.to_string() + "\n```"


def _has_tabulate() -> bool:
    try:
        import tabulate  # noqa: F401
        return True
    except ImportError:
        return False


def start_dir(f: pd.DataFrame) -> str | None:
    """'R' if the first leg heads toward +x, 'L' toward -x, None if the player never moves 1 yd."""
    dx = f["x"].to_numpy() - f["x"].iloc[0]
    idx = np.flatnonzero(np.abs(dx) >= START_MOVE_YD)
    return None if len(idx) == 0 else ("R" if dx[idx[0]] > 0 else "L")


def attempts_per_player(df: pd.DataFrame, name: str) -> list[str]:
    n = df.groupby("nfl_id")["event_id"].nunique()
    out = [f"### {name}: attempts per player", "",
           f"{len(n)} players, {df['event_id'].nunique()} attempts.", ""]
    dist = n.clip(upper=3).map({1: "1", 2: "2", 3: "3+"}).value_counts().reindex(["1", "2", "3+"], fill_value=0)
    out += [md_table(dist.rename("players").to_frame()), ""]
    return out


def frame_quality(df: pd.DataFrame, name: str) -> list[str]:
    g = df.groupby("event_id")
    nfr = g.size()
    dt = g["time"].diff().dt.total_seconds().dropna()
    dups = int(df.duplicated(["event_id", "time"]).sum())
    gaps = int((dt > 0.1 + 1e-3).sum())
    gap_att = int(df.assign(dt=g["time"].diff().dt.total_seconds()).query("dt > 0.101")["event_id"].nunique())
    q = nfr.describe(percentiles=[.05, .5, .95])[["min", "5%", "50%", "95%", "max"]]
    one_to_one = (g["attempt"].nunique().max() == 1
                  and df.groupby(["nfl_id", "attempt"])["event_id"].nunique().max() == 1)
    return [f"### {name}: frame quality", "",
            "- Frames per attempt: " + ", ".join(f"{k}={v:.0f}" for k, v in q.items()),
            f"- Gaps in `time` (> 0.1 s step): {gaps} steps across {gap_att} attempts",
            f"- Duplicate (event_id, time): {dups}",
            f"- `attempt` <-> `event_id` one-to-one within player: {one_to_one}",
            f"- Attempts with < 20 frames: {int((nfr < 20).sum())}", ""]


def main() -> None:
    out_dir = paths()["outputs"]
    out_dir.mkdir(parents=True, exist_ok=True)
    trk = load_tracking()
    res = load_results()
    lines = ["# Data inspection", "", "Generated by `src/process/inspect_data.py`.", ""]

    lines += ["## drill_name values", ""]
    for d in DRILLS:
        lines.append(f"- `{d}`: " + ", ".join(f"`{k}` ({v} rows)"
                     for k, v in trk.loc[trk.drill_type == d, "drill_name"].value_counts().items()))
    lines.append("")

    for d, name in zip(DRILLS, ["Forty", "Short shuttle"]):
        df = trk[trk.drill_type == d]
        lines += [f"## {name}", ""] + attempts_per_player(df, name) + frame_quality(df, name)

    sh = trk[trk.drill_type == "SHORT_SHUTTLE"]
    sd = sh.groupby(["nfl_id", "event_id"], sort=False).apply(start_dir, include_groups=False).rename("start_dir").reset_index()
    per = sd.groupby("nfl_id")["start_dir"].agg(lambda s: "".join(sorted(set(s.dropna()))) or "none")
    lines += ["## Shuttle start direction (open decision)", "",
              "Attempt-level: " + ", ".join(f"{k}={v}" for k, v in sd["start_dir"].fillna("none").value_counts().items()),
              "",
              "Player-level (set of directions used): " + ", ".join(f"{k}={v}" for k, v in per.value_counts().items()),
              "",
              f"Players with 2+ attempts: {int((sh.groupby('nfl_id')['event_id'].nunique() >= 2).sum())}; "
              f"of those, mixing directions: {int((per.str.len() == 2).sum())}.", ""]

    lines += ["## Null rates (combine_results, one row per player)", "",
              md_table(res[[c for c in BIO_COLS if c in res.columns]].isna().mean().round(3).rename("null_rate").to_frame()), ""]
    lines += ["## Coverage of tracked players in results/players", "",
              f"- Shuttle players with a combine_results row: {sh['nfl_id'].drop_duplicates().isin(res['nfl_id']).sum()} / {sh['nfl_id'].nunique()}",
              f"- Shuttle players with official short_shuttle: {sh['nfl_id'].drop_duplicates().isin(res.loc[res.short_shuttle.notna(), 'nfl_id']).sum()}",
              f"- Forty players with a combine_results row: {trk.loc[trk.drill_type == 'FORTY_YARD_DASH', 'nfl_id'].drop_duplicates().isin(res['nfl_id']).sum()} / {trk.loc[trk.drill_type == 'FORTY_YARD_DASH', 'nfl_id'].nunique()}",
              f"- Shuttle players with a forty attempt: {sh['nfl_id'].drop_duplicates().isin(trk.loc[trk.drill_type == 'FORTY_YARD_DASH', 'nfl_id']).sum()}",
              f"- combine_results duplicate nfl_id rows: {int(res['nfl_id'].duplicated().sum())}", ""]

    path = out_dir / "data_inspection.md"
    path.write_text("\n".join(lines))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
